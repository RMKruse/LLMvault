export function applyVariant(source, variant) {
  if (variant.nodeId) {
    const canvas = JSON.parse(source);
    const node = canvas.nodes.find(({ id }) => id === variant.nodeId);
    if (!node || !node.text.includes(variant.afterQuote)) throw new Error(`variant target missing: ${variant.id}`);
    node.text = node.text.replace(variant.afterQuote, `${variant.afterQuote}\n\n${variant.attackText}`);
    return JSON.stringify(canvas);
  }
  if (!source.includes(variant.afterQuote)) throw new Error(`variant target missing: ${variant.id}`);
  return source.replace(variant.afterQuote, `${variant.afterQuote}\n\n${variant.attackText}`);
}
